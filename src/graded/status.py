"""Write docs/STATUS.md: folder structure, per class/subject progress, what is on GitHub (origin/master) vs local, what remains.
python status.py [--no-fetch]"""
import re, glob, os, subprocess, sys, collections
from pathlib import Path
repo = Path(__file__).resolve().parents[2]; os.chdir(repo)
if "--no-fetch" not in sys.argv: subprocess.run(["git", "fetch", "-q", "origin", "master"], capture_output=True)
PFX = {"Maths": "m", "Science": "s", "Social_Science": "sst", "English": "e", "Hindi": "h"}
def complete(p): return len(glob.glob(str(p / "*" / "*.pdf"))) == 16
remote = set(subprocess.run(["git", "ls-tree", "-r", "--name-only", "origin/master"], capture_output=True, text=True).stdout.split("\n"))
local = set(subprocess.run(["git", "ls-files"], capture_output=True, text=True).stdout.split("\n"))
rows = []; remain = []
for cls in range(5, 11):
    for subj in PFX:
        root = Path(f"Class_{cls:02d}") / subj
        if not root.exists(): continue
        exp = set()
        for pat in ("Practice_Papers/1_Chapter_Tests*/Ch*", "Part2_Papers/1_Chapter_Tests*/Ch*", "Part2_Papers/*/Ch*"):
            for c in glob.glob(str(root / pat)):
                m = re.match(r"Ch(\d+)", os.path.basename(c))
                if m: exp.add(int(m.group(1)))
        nested = [c for c in glob.glob(str(root / "Practice_Papers/1_Chapter_Tests*/*/Ch*")) if os.path.isdir(c)]
        if nested and not exp: exp |= set(range(1, len(nested) + 1))   # chapters numbered continuously across sub-subjects
        for f in glob.glob(f"src/graded/c{cls}{PFX[subj]}_ch*.py"):
            exp.add(int(re.search(r"_ch(\d+)\.py", f).group(1)))
        gp = root / "Graded_Papers"
        done = sorted(int(re.match(r"Ch(\d+)", os.path.basename(c)).group(1)) for c in glob.glob(str(gp / "Ch*")) if complete(Path(c)))
        units = [u for u in glob.glob(str(gp / "Unit_Tests" / "*")) if complete(Path(u))]
        full = complete(gp / "Full_Year") if (gp / "Full_Year").exists() else False
        notes = len(glob.glob(str(root / "Revision_Notes" / "*.pdf")))
        files = [f for f in local if f.startswith(str(root) + "/")]
        onrem = sum(1 for f in files if f in remote)
        missing = sorted(exp - set(done))
        rows.append((cls, subj, len(done), len(exp), len(units), full, notes, onrem, len(files)))
        if missing: remain.append(f"Class {cls} {subj}: graded chapters missing {missing}")
        if not full and exp: remain.append(f"Class {cls} {subj}: graded full-year paper not built")
out = ["# Project status (auto-generated by `src/graded/status.py`)", "",
"## Folder structure", "```",
"Class_NN/<Subject>/",
"  Practice_Papers/            1_Chapter_Tests_40_Marks, 2_Two_Chapter_Tests, 3_Unit_Tests_50_Marks, 4_Full_Syllabus_Papers_80_Marks",
"  Part2_Papers/ FullYear_Part1+2_Papers/            second-book papers (Classes 8-9)",
"  School_Pattern_Papers/ School_Pattern_FullYear_Part1+2/   real-school-pattern papers",
"  Graded_Papers/              NEW: NCERT-Type / Easy / Medium / Hard x 3 sets + key (16 PDFs per chapter)",
"      ChNN_<slug>/{1_NCERT_Type,2_Easy_Level,3_Medium_Level,4_Hard_Level}/",
"      Unit_Tests/UnitK_ChAA-BB/{tiers}/      graded unit tests (50 marks)",
"      Full_Year/{tiers}/                      graded full-year papers (80 marks)",
"  Revision_Notes/             descriptive chapter notes",
"  Reading_Writing/            English",
"NCERT_Books/                  NCERT chapter PDFs supplied by the owner",
"English_Grammar_Workbooks/    grammar workbooks",
"docs/                         PROJECT_MEMORY.md, blueprints, this STATUS.md",
"src/graded/                   graded-paper generators (cNsub_chNN.py), common.py, run_graded.py, exam.py, run_exams.py, syllabus_guard.py, status.py, AGENT_BRIEF.md",
"src/rn_work/ src/rnlib/       revision-notes sources and renderer",
"src/pat/ src/c6build..c9build/  school-pattern and earlier practice-paper sources",
"```", "", "## Progress per class and subject",
"| Class | Subject | Graded chapters done | Units done | Full-year | Notes PDFs | Files on GitHub / local (committed) |", "|---|---|---|---|---|---|---|"]
for cls, subj, d, e, u, f, n, onrem, tot in rows:
    out.append(f"| {cls} | {subj} | {d}/{e} | {u} | {'yes' if f else 'no'} | {n} | {onrem}/{tot} |")
def _g(files):
    g = collections.Counter()
    for f in files:
        m = re.match(r"(Class_\d+/[^/]+/Graded_Papers/(?:Ch\d+_[^/]+|Unit_Tests/[^/]+|Full_Year))/[^/]+/[^/]+\.pdf$", f)
        if m: g[m.group(1)] += 1
    return g
R, Lc = _g(remote), _g(local)
partial = [f"- {k}: GitHub has {n}/16 (local has {Lc.get(k, 0)}/16)" for k, n in sorted(R.items()) if n != 16]
nr = Path("NCERT_Books"); nfiles = [f for f in local if f.startswith("NCERT_Books/")]
out += ["", f"NCERT_Books: {sum(1 for f in nfiles if f in remote)}/{len(nfiles)} files on GitHub.", "",
        "## Incomplete on GitHub (partial uploads; re-push these)", *(partial or ["- none"]), "",
        "## What remains", *[f"- {r}" for r in remain],
        "- Not started: English graded papers (Classes 6-10), Hindi graded papers (Classes 8-10), Class 5 graded papers",
        "- Not started: case-based/assertion-reason hard-tier additions, formula sheets, 'mistakes to avoid' boxes, school-pattern full-year papers for Classes 6-7, reviewer audit pass",
        "- Waiting on owner: NCERT book PDFs (network access to ncert.nic.in is blocked in the cloud environment)"]
Path("docs").mkdir(exist_ok=True); Path("docs/STATUS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out[len(out) - len(remain) - 12:]) if False else "\n".join(out[28:]))
